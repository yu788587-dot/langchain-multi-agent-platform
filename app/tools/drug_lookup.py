def _format(name: str, info: dict) -> str:
    lines = [f"【{name}】（内置演示数据）"]
    lines += [f"{key}：{info[key]}" for key in ("适应症", "用法用量", "禁忌", "注意事项")]
    lines.append("以上信息仅供参考，具体用药请遵医嘱或咨询药师。")
    return "\n".join(lines)


@tool
def drug_lookup(drug_name: str) -> str:
    """查询常见药品的适应症、用法用量与禁忌。输入药品名称，例如"布洛芬"。"""
    q = (drug_name or "").strip()
    if q:
        for name, info in _DRUG_DB.items():
            if name in q or q in name:
                return _format(name, info)
    return f"药品库中未收录「{q}」。当前为内置演示数据，仅涵盖：{'、'.join(_DRUG_DB)}。"
